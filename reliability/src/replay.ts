import { tmpdir } from 'node:os';
import { join } from 'node:path';
import type { TallyEvent } from '@tally/contract';
import { initDatabase } from '@tally/db';
import { computeTotalCents } from '@tally/contract';
import { FakeClock } from './clock.js';
import { checkSpokenDrift } from './drift.js';
import { Store, type CommitRequest, type ReplayRunRow } from './committer.js';
import { EvidenceTracker } from './evidence.js';
import { Gate, type GateOptions } from './gate.js';
import { Ingest } from './ingest.js';
