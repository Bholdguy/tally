// STEP 8: replay. Two tiers, never conflated (PRD G7/G8, DECISIONS F11):
//
//  EVIDENCE TIER: the case's stored events are re-fed through the CURRENT ingest -> evidence tracker -> extractor -> gate, on a
//    virtual clock, in a throwaway replay-mode database. Nothing in it is random or wall-clock dependent, so the verdict AND the
//    stored diff are byte-identical run to run. This is the ONLY tier the word "deterministic" applies to.
//  AUDIO TIER: the stored PCM is streamed at 1x through a fresh live-agent session (server/src/replay-audio.ts). The managed
//    LLM is not seedable, so it is run k times and reported as "k/3 passed"; it is never called deterministic here or anywhere.
//
// What a replay asks (and does not ask): "does the CURRENT build still handle this recorded call correctly?"
//   * with an expected state (a repair that RESOLVED): the recorded call is judged against what the customer validated. A call
//     that would have produced a different line than expected must be HELD; a call that matches it must be ALLOWED.
//   * without one (escalated / unresolved / no repair): the only claim is the fail-closed one, "a held call stays held".
